# ── 편의 함수 ──────────────────────────────
def find_replace(old, new):
    f = doc.Content.Find
    f.ClearFormatting()
    f.Replacement.ClearFormatting()
    f.Text = old
    f.Replacement.Text = new
    f.MatchCase = True
    f.MatchWholeWord = False
    result = f.Execute(Replace=wdReplaceAll)
    if result:
        print(f'  교체: "{old}" → "{new}"')
    return result

def find_replace_page(old_page, new_page, section_hint):
    """목차의 탭+페이지 부분만 교체"""
    # 탭문자(\t)를 ^t 로 표현
    old = f'^t{old_page}'
    new = f'^t{new_page}'
    f = doc.Content.Find
    f.ClearFormatting()
    f.Replacement.ClearFormatting()
    f.Text = old
    f.Replacement.Text = new
    f.MatchCase = True
    result = f.Execute(Replace=wdReplaceAll)
    if result:
        print(f'  페이지 교체 ({section_hint}): {old_page} → {new_page}')
    return result

